#!/usr/bin/env python3
"""The helper's check tables, from the committed hash lists (names and hashes only).

    python3 tools/install-data/hashes.py OUT.h

  disk[]:      reference/disk-files.sha256, every file on the 7 disks
  installed[]: reference/install.sha256, the original installer's WING2 tree, as paths
               under the destination (GAMEDAT/NAME, WC2.EXE, WC2.CFG)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rows(name, strip=''):
    out = []
    for line in (ROOT / 'reference' / name).read_text().splitlines():
        if line.strip():
            sha, path = line.split(None, 1)
            if path.startswith(strip):
                out.append((path[len(strip):], bytes.fromhex(sha)))
    return sorted(out)


def table(name, entries):
    lines = [f'static const Hash {name}[{len(entries)}] = {{']
    for path, sha in entries:
        lines.append(f'    {{"{path}", {{' + ','.join(f'0x{b:02x}' for b in sha) + '}},')
    lines.append('};')
    return lines


def main():
    disk = rows('disk-files.sha256')
    installed = rows('install.sha256', './WING2/')
    text = ['/* Generated by tools/install-data/hashes.py from reference/disk-files.sha256 and install.sha256; do not edit. */',
            'typedef struct { const char *name; unsigned char sha[32]; } Hash;']
    text += table('disk', disk) + table('installed', installed)
    Path(sys.argv[1]).write_text('\n'.join(text) + '\n')


if __name__ == '__main__':
    main()
